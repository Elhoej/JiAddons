"""Builds the font variants in JiCombatFont/Media from the fonts there, and
the XML font objects the incoming combat text uses.

- Media/Spaced/<key>_<step>.ttf: WoW has no letter-spacing API, so spacing is
  baked into the files. Every glyph's advance width grows (or shrinks) by
  <step>% of the em size, e.g. galaxy_p10.ttf (+10%), galaxy_m5.ttf (-5%).
- IncomingFonts.xml: one font object per font and spacing, named
  JiCombatFont_<key>[_<step>], with the attributes of Blizzard's
  SystemFont_World (height 64, fixedSize, filter, shadow). fixedSize can only
  be set in XML, and without it Blizzard's SetTextHeight spreads the letters.

Keep STEPS in sync with ns.SPACINGS in Core.lua (a test checks the files).

    python3 -m pip install fonttools
    python3 JiCombatFont/tools/make_font_variants.py
"""
import glob
import os
import shutil

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont

STEPS = [-10, -5, 5, 10, 15, 20, 30]

# Combat text is numbers and Latin/Cyrillic/Greek words; dropping other
# scripts (BalooBhaina carries Oriya) keeps the copies small.
UNICODES = (
    list(range(0x20, 0x250)) + list(range(0x370, 0x530)) + list(range(0x1E00, 0x1F00))
    + list(range(0x2000, 0x2070)) + [0x20AC, 0x2122]
)
# Precomputed per-size advance tables would contradict the new widths.
DROP = ["hdmx", "LTSH", "VDMX", "DSIG", "FFTM"]

here = os.path.dirname(os.path.abspath(__file__))
media = os.path.join(here, "..", "JiCombatFont", "Media")
spaced_dir = os.path.join(media, "Spaced")
shutil.rmtree(spaced_dir, ignore_errors=True)
shutil.rmtree(os.path.join(media, "Tight"), ignore_errors=True)  # removed in 0.5
os.makedirs(spaced_dir)
xml_path = os.path.join(here, "..", "JiCombatFont", "IncomingFonts.xml")

XML_HEAD = """<Ui xmlns="http://www.blizzard.com/wow/ui/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://www.blizzard.com/wow/ui/ ..\\FrameXML\\UI.xsd">
\t<!-- Generated by tools/make_font_variants.py. Do not edit. -->
"""
XML_FONT = """\t<Font name="JiCombatFont_%s" font="Interface\\AddOns\\JiCombatFont\\Media\\%s.ttf" height="64" filter="true" fixedSize="true" virtual="true">
\t\t<Shadow>
\t\t\t<Offset>
\t\t\t\t<AbsDimension x="1" y="-1"/>
\t\t\t</Offset>
\t\t\t<Color r="0" g="0" b="0"/>
\t\t</Shadow>
\t</Font>
"""


def file_name(key, step):
    if step == 0:
        return key + ".ttf"
    return "%s_%s%d.ttf" % (key, "p" if step > 0 else "m", abs(step))


def build(path, step):
    font = TTFont(path)
    opts = Options()
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    opts.hinting = False  # combat text is large; halves the file size
    opts.drop_tables += DROP
    sub = Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)

    delta = round(font["head"].unitsPerEm * step / 100)
    hmtx = font["hmtx"]
    for glyph, (advance, lsb) in hmtx.metrics.items():
        if advance > 0:  # leave zero-width marks alone
            hmtx.metrics[glyph] = (max(1, advance + delta), lsb)
    font["hhea"].advanceWidthMax = max(a for a, _ in hmtx.metrics.values())
    return font


count = 0
xml = [XML_HEAD]
for path in sorted(glob.glob(os.path.join(media, "*.ttf")), key=lambda p: os.path.basename(p).lower()):
    key = os.path.splitext(os.path.basename(path))[0]
    for step in [0] + STEPS:
        name = file_name(key, step)[:-4]
        if step == 0:
            xml.append(XML_FONT % (name, name))
        else:
            build(path, step).save(os.path.join(spaced_dir, name + ".ttf"))
            xml.append(XML_FONT % (name, "Spaced\\" + name))
            count += 1
xml.append("</Ui>\n")
with open(xml_path, "w") as f:
    f.write("".join(xml))

total = sum(os.path.getsize(p) for p in glob.glob(os.path.join(spaced_dir, "*.ttf")))
print("wrote %d fonts (%.1f MB) and %d font objects" % (count, total / 1e6, len(xml) - 2))
