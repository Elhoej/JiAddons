local addonName, ns = ...

ns.name = addonName
ns.title = "JiCombatFont"

local MEDIA = "Interface\\AddOns\\" .. addonName .. "\\Media\\"

-- key is the file name in Media\ without ".ttf"; "default" is Blizzard's font.
ns.FONTS = {
    { key = "default", name = "Blizzard default" },
    { key = "BalooBhaina", name = "Baloo Bhaina" },
    { key = "Bungee", name = "Bungee" },
    { key = "CaesarDressing", name = "Caesar Dressing" },
    { key = "CoveredByYourGrace", name = "Covered By Your Grace" },
    { key = "galaxy", name = "Galaxy" },
    { key = "JotiOne", name = "Joti One" },
    { key = "LondrinaSolid", name = "Londrina Solid" },
    { key = "NovaFlat", name = "Nova Flat" },
    { key = "Roboto", name = "Roboto" },
    { key = "SedgwickAveDisplay", name = "Sedgwick Ave Display" },
    { key = "Share", name = "Share" },
    { key = "ShareBold", name = "Share Bold" },
    { key = "Sniglet", name = "Sniglet" },
    { key = "SquadaOne", name = "Squada One" },
}
local byKey = {}
for _, f in ipairs(ns.FONTS) do byKey[f.key] = f end

-- Letter spacing in percent of the font size. WoW has no letter-spacing API,
-- so each step is a pre-built copy of every font in Media\Spaced\ (made by
-- tools/make_font_variants.py; keep its STEPS in sync).
ns.SPACINGS = { -10, -5, 0, 5, 10, 15, 20, 30 }
local validSpacing = {}
for _, v in ipairs(ns.SPACINGS) do validSpacing[v] = true end

ns.defaults = {
    outgoing = "galaxy",
    incoming = "galaxy",
    outgoingSpacing = 0,
    incomingSpacing = 0,
}

-- Outgoing numbers are sized by this CVar rather than by the font.
ns.WORLD_TEXT_SCALE = "WorldTextScale"

-- Blizzard's own fonts, captured before they're replaced. GameFonts.xml sets
-- DAMAGE_TEXT_FONT per locale before any addon loads.
local blizzardDamageFont = DAMAGE_TEXT_FONT or "Fonts\\FRIZQT__.TTF"

-- CombatTextFont inherits SystemFont_World: a 64-high fixedSize font that
-- Blizzard draws at whatever SetTextHeight asks for (25; crits 30-60).
-- Font:SetFont drops fixedSize, after which letters keep their full-size
-- spacing but are drawn at 25 ("E N T E R I N G"). So the incoming fonts are
-- XML font objects with the same attributes (IncomingFonts.xml, generated by
-- tools/make_font_variants.py) and CombatTextFont is re-parented onto them.
local blizzardCombat -- { parent = original parent font object, path = file }

-- CombatTextFont is created by the client; returns it once its original
-- settings are captured.
local function CombatFont()
    local font = CombatTextFont
    if type(font) ~= "table" or not font.SetFontObject then return end
    if not blizzardCombat then
        local parent = font:GetFontObject()
        if type(parent) ~= "table" then parent = SystemFont_World end
        blizzardCombat = { parent = parent, path = font:GetFont() or blizzardDamageFont }
    end
    return font
end

-- File name (without .ttf) of a bundled font at a spacing, and whether it's a
-- spaced copy. nil for Blizzard's font, which the addon has no file for.
local function FileName(key, spacing)
    if key == "default" or not byKey[key] then return end
    if spacing and spacing ~= 0 and validSpacing[spacing] then
        return key .. (spacing > 0 and "_p" or "_m") .. math.abs(spacing), true
    end
    return key, false
end

-- kind is "outgoing" or "incoming". Unknown keys fall back to Blizzard's font.
function ns.FontPath(key, kind, spacing)
    local file, spaced = FileName(key, spacing)
    if file then
        return MEDIA .. (spaced and "Spaced\\" or "") .. file .. ".ttf"
    end
    if kind == "incoming" and CombatFont() then return blizzardCombat.path end
    return blizzardDamageFont
end

-- The XML font object for incoming text; nil for Blizzard's font.
function ns.IncomingFontName(key, spacing)
    local file = FileName(key, spacing)
    return file and ("JiCombatFont_" .. file)
end

-- Outgoing: the numbers above whatever you hit. The client reads this global
-- when the world loads, so a change only shows after a relog.
function ns.ApplyOutgoing()
    DAMAGE_TEXT_FONT = ns.FontPath(ns.db.outgoing, "outgoing", ns.db.outgoingSpacing)
end

-- Incoming: Blizzard's scrolling combat text around the player
-- (Blizzard_CombatText, load on demand). Every message calls
-- SetFontObject(CombatTextFont), so changing its parent applies at once.
function ns.ApplyIncoming()
    local font = CombatFont()
    if not font then return false end
    local name = ns.IncomingFontName(ns.db.incoming, ns.db.incomingSpacing)
    local target = name and _G[name]
    if type(target) ~= "table" then target = blizzardCombat.parent end
    if type(target) ~= "table" then return false end
    font:SetFontObject(target)
    return true
end

-- The outgoing scale CVar; nil when this client doesn't have it.
local function GetCVarValue(name)
    if C_CVar and C_CVar.GetCVar then return C_CVar.GetCVar(name) end
    return GetCVar and GetCVar(name)
end

function ns.GetOutgoingScale()
    return tonumber(GetCVarValue(ns.WORLD_TEXT_SCALE))
end

function ns.SetOutgoingScale(v)
    if C_CVar and C_CVar.SetCVar then
        C_CVar.SetCVar(ns.WORLD_TEXT_SCALE, v)
    else
        SetCVar(ns.WORLD_TEXT_SCALE, v)
    end
end

function ns.Apply()
    ns.ApplyOutgoing()
    ns.ApplyIncoming()
end

-- True when the outgoing font was changed since login and needs a relog.
function ns.OutgoingPending()
    return ns.loginOutgoing ~= nil and DAMAGE_TEXT_FONT ~= ns.loginOutgoing
end

-------------------------------------------------------------------------------
-- Startup
-------------------------------------------------------------------------------

-- ADDON_LOADED comes before the world loads, early enough for DAMAGE_TEXT_FONT.
ns:OnLoad(function()
    ns.db = ns.LoadSavedVariables("JiCombatFontDB", ns.defaults)
    -- Settings from 0.3/0.4 that were built on a wrong diagnosis.
    ns.db.incomingSize, ns.db.incomingTightMinus = nil, nil
    ns.Apply()
    ns.loginOutgoing = DAMAGE_TEXT_FONT
    ns.Options:Init()
end)

ns:RegisterEvent("ADDON_LOADED", function(_, name)
    if name == "Blizzard_CombatText" and ns.db then ns.ApplyIncoming() end
end)
ns:RegisterEvent("PLAYER_LOGIN", function()
    if ns.db then ns.ApplyIncoming() end
end)

SLASH_JICOMBATFONT1 = "/jicombatfont"
